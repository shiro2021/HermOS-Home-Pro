/*
 * HermOS theme_engine — resolution-independent theming.
 *
 * Reads /themes/default/theme.hid (all layout values are PERCENTAGES, 0-100)
 * and receives the exact screen dimensions from desktop_builder via the
 * "screen_state" Report (as a ROM). It converts every percentage to absolute
 * pixels (absolute = percentage * screen / 100) and publishes the result as
 * the "theme_state" Report. desktop_builder consumes only absolute pixels
 * and never does percentage math.
 */

#include <base/component.h>
#include <base/attached_rom_dataspace.h>
#include <base/log.h>
#include <base/signal.h>
#include <os/reporter.h>
#include <util/xml_generator.h>
#include <util/string.h>
#include <base/heap.h>
#include <os/vfs.h>

using namespace Genode;

namespace Theme {

	struct Main
	{
		Genode::Env &_env;

		Genode::Reporter _theme { _env, "theme_state", "theme_state", 4096 };

		/* Step 2: the config ROM generated by the desktop_builder (our parent)
		 * carries the exact screen size as root attributes. */
		Attached_rom_dataspace _config { _env, "config" };

		/* native VFS front-end (replaces the libc open/read path) */
		Genode::Heap   _heap { _env.ram(), _env.rm() };
		Root_directory _vfs  { _env, _heap };

		int _screen_w { 0 }, _screen_h { 0 };

		/* the parsed theme (percentages) */
		enum { MAX_CELLS = 6 };
		struct Cell { char id[16]; int x, y, w, h, chamfer; };
		Cell _cells[MAX_CELLS] { };
		int  _cell_count { 0 };

		int  _sb_x { 0 }, _sb_y { 0 }, _sb_w { 0 }, _sb_h { 0 };

		/* geometry unit: values are fractions of the screen in 1/_scale
		 * (100 = percent, the legacy unit; 10000 = 0.01 % steps) */
		int  _scale { 100 };

		/* Shiro Command Bar (fractions of the screen, see theme.hid) */
		struct Cmdbar { bool set; int x, y, w, font, pad_x, pad_y, spacing, tip, greet_font, sub_font; };
		Cmdbar _cb { };

		/* Cell frame look: lengths are fractions of the screen height (1/_scale), alpha in percent,
		 * colours "R,G,B" (see theme.hid) */
		struct Frame { bool set; int border, glow_reach, glow_sigma, glow_alpha, shadow_reach, shadow_sigma, shadow_alpha; };
		Frame _fr { false, 16, 160, 55, 58, 80, 30, 38 };
		char _fr_glow[16]     { "255,112,22" };
		char _fr_active_a[16] { "255,200,126" };
		char _fr_active_b[16] { "226,92,20" };
		char _fr_carbon_a[16] { "92,96,102" };
		char _fr_carbon_b[16] { "48,51,56" };

		/* OS-wide ink: accent for active elements, carbon gray for inactive ones ("R,G,B") */
		bool _ink_set { false };
		int  _ink_dim { 40 };
		char _ink_accent[16]      { "255,156,48" };
		char _ink_carbon[16]      { "138,143,150" };
		char _ink_carbon_text[16] { "168,172,178" };

		/* default geometry of a newly launched app Cell */
		struct Appcell { bool set; int x, y, w, h, cascade; };
		Appcell _ac { };

		/* Plasma-style panels */
		char _pl_mode[16] { "autohide" };
		char _pb_mode[16] { "visible" };
		int  _pl_size { 78 }, _pb_size { 28 };

		/* Step 3: the normalized snap slots (quick tiling) */
		enum { MAX_SNAPS = 4 };
		struct Snap { char id[16]; int x, w; };
		Snap _snaps[MAX_SNAPS] { };
		int  _snap_count { 0 };

		char _glass[32]    { "13,18,30,220" };
		char _active[32]   { "255,140,40,255" };
		char _inactive[32] { "40,60,80,255" };
		char _paused[32]   { "150,150,150,255" };

		/* Step 1: the icon asset paths (published in the icons node) */
		char _icon_close[64]    { "/assets/icon_close.png" };
		char _icon_minimize[64] { "/assets/icon_minimize.png" };
		char _icon_mic[64]      { "/assets/icon_mic.png" };
		char _icon_pause[64]    { "/assets/icon_pause.png" };

		Main(Genode::Env &env) : _env(env)
		{
			log("Theme Engine initialized.");

			/* apply the <vfs> config from our config ROM (mount /themes) */
			_config.node().with_optional_sub_node("vfs", [&] (Node const &vfs) {
				_vfs.apply_config(vfs);
			});

			_load_hid();

			/* Step 2: the screen size comes from OUR OWN config, generated
			 * by the desktop_builder at spawn time — no screen_state report */
			_screen_w = (int)_config.xml().attribute_value("width",  0UL);
			_screen_h = (int)_config.xml().attribute_value("height", 0UL);

			if (_screen_w < 1 || _screen_h < 1) {
				Genode::error("Theme Engine: invalid screen size in config");
				return;
			}

			_publish();
		}

		/* load + parse /themes/default/theme.hid (percentages) */
		void _load_hid()
		{
			/* the <rom> VFS plugin reports the PAGE-ALIGNED dataspace size
			 * (4096), not the logical file size, so the buffer must be at
			 * least one page. The zero padding is ignored by _parse. */
			char buf[8192];
			try {
				size_t const size = (size_t)_vfs.file_size("/themes/default/theme.hid");
				if (size == 0 || size > sizeof(buf)) {
					Genode::error("Theme Engine: bad theme.hid size");
					return;
				}
				Readonly_file file(_vfs, "/themes/default/theme.hid");
				size_t const n = file.read(Byte_range_ptr(buf, size));
				if (n != size) {
					Genode::error("Theme Engine: short read of theme.hid");
					return;
				}
				_parse(buf, n);
			} catch (...) {
				Genode::error("Theme Engine: failed to open theme.hid");
			}
		}

		/* parse the HID: "+"-indented tree with "key: value" lines */
		void _parse(char const *buf, size_t len)
		{
			enum Sect { SECT_NONE, SECT_CELL, SECT_SIDEBAR, SECT_ICONS, SECT_SNAP, SECT_PLEFT, SECT_PBOTTOM, SECT_CMDBAR, SECT_APPCELL, SECT_FRAME, SECT_INK } sect = SECT_NONE;
			Cell *cur = nullptr;
			Snap *scur = nullptr;

			char const *p = buf;
			char const *const end = buf + len;
			while (p < end) {
				/* one line */
				char const *ls = p;
				while (p < end && *p != '\n') ++p;
				char const *le = p;
				if (p < end) ++p;

				/* trim the "+" markers + the whitespace */
				while (ls < le && (*ls == ' ' || *ls == '\t' || *ls == '+')) ++ls;
				while (le > ls && (le[-1] == ' ' || le[-1] == '\t' || le[-1] == '\r')) --le;
				if (ls >= le || *ls == '#') continue;

				/* find the "key: value" separator */
				char const *colon = nullptr;
				for (char const *q = ls; q < le; ++q)
					if (*q == ':') { colon = q; break; }

				if (!colon) {
					/* a section marker ("theme", "colors", "layout", "slot", "sidebar") */
					char word[24];
					size_t const wl = (size_t)(le - ls);
					size_t const cp = wl < 23 ? wl : 23;
					Genode::memcpy(word, ls, cp);
					word[cp] = 0;

					if      (Genode::strcmp(word, "slot") == 0)    { sect = SECT_CELL;
					                                                 if (_cell_count < MAX_CELLS)
					                                                     { cur = &_cells[_cell_count++]; cur->id[0] = 0; } }
					else if (Genode::strcmp(word, "sidebar") == 0) { sect = SECT_SIDEBAR; cur = nullptr; }
					else if (Genode::strcmp(word, "layout") == 0)  { sect = SECT_NONE;    cur = nullptr; }
					else if (Genode::strcmp(word, "colors") == 0)  { sect = SECT_NONE;    cur = nullptr; }
					else if (Genode::strcmp(word, "icons") == 0)   { sect = SECT_ICONS;   cur = nullptr; }
				else if (Genode::strcmp(word, "snap") == 0)  { sect = SECT_SNAP;
				                                               if (_snap_count < MAX_SNAPS)
				                                                   { scur = &_snaps[_snap_count++]; scur->id[0] = 0; } }
				else if (Genode::strcmp(word, "snaps") == 0) { sect = SECT_NONE;  cur = nullptr; scur = nullptr; }
				else if (Genode::strcmp(word, "panels") == 0) { sect = SECT_NONE;  cur = nullptr; scur = nullptr; }
				else if (Genode::strcmp(word, "commandbar") == 0) { sect = SECT_CMDBAR; cur = nullptr; scur = nullptr; }
				else if (Genode::strcmp(word, "appcell") == 0)    { sect = SECT_APPCELL; cur = nullptr; scur = nullptr; }
				else if (Genode::strcmp(word, "frame") == 0)      { sect = SECT_FRAME;   cur = nullptr; scur = nullptr; }
				else if (Genode::strcmp(word, "ink") == 0)        { sect = SECT_INK;     cur = nullptr; scur = nullptr; }
				else if (Genode::strcmp(word, "left") == 0)   { sect = SECT_PLEFT;   cur = nullptr; scur = nullptr; }
				else if (Genode::strcmp(word, "bottom") == 0) { sect = SECT_PBOTTOM; cur = nullptr; scur = nullptr; }
					continue;
				}

				/* the key */
				char key[24];
				size_t const kl = (size_t)(colon - ls);
				size_t const kcp = kl < 23 ? kl : 23;
				Genode::memcpy(key, ls, kcp);
				key[kcp] = 0;

				/* the value (skip the whitespace after the colon) */
				char const *vs = colon + 1;
				while (vs < le && (*vs == ' ' || *vs == '	')) ++vs;

				/* remember the value start before the integer parse advances it */
				char const *const val_start = vs;

				/* the integer value */
				int val = 0;
				while (vs < le && *vs >= '0' && *vs <= '9') { val = val * 10 + (*vs - '0'); ++vs; }

				if (sect == SECT_APPCELL) {
					static struct { char const *k; int *v; } const map[] = {
						{ "x", &_ac.x }, { "y", &_ac.y }, { "w", &_ac.w }, { "h", &_ac.h }, { "cascade", &_ac.cascade } };
					for (auto const &m : map) if (Genode::strcmp(key, m.k) == 0) { *m.v = val; _ac.set = true; }
				} else if (sect == SECT_INK) {
					if      (Genode::strcmp(key, "accent") == 0)      { _copy_val(_ink_accent, val_start, le);      _ink_set = true; }
					else if (Genode::strcmp(key, "carbon") == 0)      { _copy_val(_ink_carbon, val_start, le);      _ink_set = true; }
					else if (Genode::strcmp(key, "carbon_text") == 0) { _copy_val(_ink_carbon_text, val_start, le); _ink_set = true; }
					else if (Genode::strcmp(key, "carbon_dim") == 0)  { _ink_dim = val; _ink_set = true; }
				} else if (sect == SECT_FRAME) {
					static struct { char const *k; int *v; } const map[] = {
						{ "border", &_fr.border }, { "glow_reach", &_fr.glow_reach }, { "glow_sigma", &_fr.glow_sigma },
						{ "glow_alpha", &_fr.glow_alpha }, { "shadow_reach", &_fr.shadow_reach },
						{ "shadow_sigma", &_fr.shadow_sigma }, { "shadow_alpha", &_fr.shadow_alpha } };
					static struct { char const *k; char *v; } const cols[] = {
						{ "glow", _fr_glow }, { "active_a", _fr_active_a }, { "active_b", _fr_active_b },
						{ "carbon_a", _fr_carbon_a }, { "carbon_b", _fr_carbon_b } };
					for (auto const &m : map)  if (Genode::strcmp(key, m.k) == 0) { *m.v = val; _fr.set = true; }
					for (auto const &c : cols) if (Genode::strcmp(key, c.k) == 0) { _copy_val(c.v, val_start, le); _fr.set = true; }
				} else if (sect == SECT_CMDBAR) {
					static struct { char const *k; int *v; } const map[] = {
						{ "x", &_cb.x }, { "y", &_cb.y }, { "w", &_cb.w }, { "font", &_cb.font },
						{ "pad_x", &_cb.pad_x }, { "pad_y", &_cb.pad_y }, { "spacing", &_cb.spacing },
						{ "tip", &_cb.tip }, { "greet_font", &_cb.greet_font }, { "sub_font", &_cb.sub_font } };
					for (auto const &m : map) if (Genode::strcmp(key, m.k) == 0) { *m.v = val; _cb.set = true; }
				} else if (Genode::strcmp(key, "scale") == 0) {
					if (val >= 100) _scale = val;
				} else if (Genode::strcmp(key, "mode") == 0 && (sect == SECT_PLEFT || sect == SECT_PBOTTOM)) {
					_copy_val(sect == SECT_PLEFT ? _pl_mode : _pb_mode, val_start, le);
				} else if (Genode::strcmp(key, "size") == 0 && (sect == SECT_PLEFT || sect == SECT_PBOTTOM)) {
					(sect == SECT_PLEFT ? _pl_size : _pb_size) = val;
				} else if (Genode::strcmp(key, "id") == 0 && sect == SECT_CELL && cur) {
					size_t const il = (size_t)(le - val_start);
					size_t const icp = il < 15 ? il : 15;
					Genode::memcpy(cur->id, val_start, icp);
					cur->id[icp] = 0;
				} else if (Genode::strcmp(key, "id") == 0 && sect == SECT_SNAP && scur) {
					size_t const il = (size_t)(le - val_start);
					size_t const icp = il < 15 ? il : 15;
					Genode::memcpy(scur->id, val_start, icp);
					scur->id[icp] = 0;
				} else if (Genode::strcmp(key, "x") == 0) {
					if (sect == SECT_CELL && cur) cur->x = val;
					else if (sect == SECT_SIDEBAR)  _sb_x = val;
					else if (sect == SECT_SNAP && scur) scur->x = val;
				} else if (Genode::strcmp(key, "y") == 0) {
					if (sect == SECT_CELL && cur) cur->y = val;
					else if (sect == SECT_SIDEBAR)  _sb_y = val;
				} else if (Genode::strcmp(key, "w") == 0) {
					if (sect == SECT_CELL && cur) cur->w = val;
					else if (sect == SECT_SIDEBAR)  _sb_w = val;
					else if (sect == SECT_SNAP && scur) scur->w = val;
				} else if (Genode::strcmp(key, "h") == 0) {
					if (sect == SECT_CELL && cur) cur->h = val;
					else if (sect == SECT_SIDEBAR)  _sb_h = val;
				} else if ((Genode::strcmp(key, "chamfer") == 0 || Genode::strcmp(key, "chamfer_percent") == 0) && sect == SECT_CELL && cur) {
					cur->chamfer = val;
				} else if (Genode::strcmp(key, "glass") == 0) {
					_copy_val(_glass, val_start, le);
				} else if (Genode::strcmp(key, "active") == 0) {
					_copy_val(_active, val_start, le);
				} else if (Genode::strcmp(key, "inactive") == 0) {
					_copy_val(_inactive, val_start, le);
				} else if (Genode::strcmp(key, "paused") == 0) {
					_copy_val(_paused, val_start, le);
				} else if (Genode::strcmp(key, "close") == 0 && sect == SECT_ICONS) {
					_copy_val(_icon_close, val_start, le);
				} else if (Genode::strcmp(key, "minimize") == 0 && sect == SECT_ICONS) {
					_copy_val(_icon_minimize, val_start, le);
				} else if (Genode::strcmp(key, "mic") == 0 && sect == SECT_ICONS) {
					_copy_val(_icon_mic, val_start, le);
				} else if (Genode::strcmp(key, "pause") == 0 && sect == SECT_ICONS) {
					_copy_val(_icon_pause, val_start, le);
				}
			}
		}

		static void _copy_val(char *dst, char const *vs, char const *le)
		{
			size_t const l = (size_t)(le - vs);
			size_t const cp = l < 31 ? l : 31;
			Genode::memcpy(dst, vs, cp);
			dst[cp] = 0;
		}

		/* convert the percentages to absolute pixels + publish theme_state */
		void _publish()
		{
			_theme.enabled(true);
			(void)_theme.generate_xml([&] (Genode::Xml_generator &xml) {
				xml.node("theme", [&] () {
					xml.node("colors", [&] () {
						xml.attribute("glass",    _glass);
						xml.attribute("active",   _active);
						xml.attribute("inactive", _inactive);
						xml.attribute("paused",   _paused);
					});
					xml.node("icons", [&] () {
						xml.attribute("close",    _icon_close);
						xml.attribute("minimize", _icon_minimize);
						xml.attribute("mic",      _icon_mic);
						xml.attribute("pause",    _icon_pause);
					});
					xml.node("layout", [&] () {
						for (int i = 0; i < _cell_count; ++i) {
							Cell const &c = _cells[i];

							int abs_x = c.x * _screen_w / _scale;
							int abs_y = c.y * _screen_h / _scale;
							int abs_w = c.w * _screen_w / _scale;
							int abs_h = c.h * _screen_h / _scale;

							/* the chamfer stays a PERCENTAGE: the desktop computes
							 * chamfer_px = pct * min(w, h) / 100 live per frame so it
							 * survives resizing without degenerating */
							xml.node("slot", [&] () {
								xml.attribute("id",      c.id);
								xml.attribute("x",       abs_x);
								xml.attribute("y",       abs_y);
								xml.attribute("w",       abs_w);
								xml.attribute("h",       abs_h);
								xml.attribute("chamfer", c.chamfer);
							});
						}
					});
					xml.node("sidebar", [&] () {
						xml.attribute("x", _sb_x * _screen_w / _scale);
						xml.attribute("y", _sb_y * _screen_h / _scale);
						xml.attribute("w", _sb_w * _screen_w / _scale);
						xml.attribute("h", _sb_h * _screen_h / _scale);
					});
					if (_ac.set) xml.node("appcell", [&] () {
						xml.attribute("x",       _ac.x * _screen_w / _scale);
						xml.attribute("y",       _ac.y * _screen_h / _scale);
						xml.attribute("w",       _ac.w * _screen_w / _scale);
						xml.attribute("h",       _ac.h * _screen_h / _scale);
						xml.attribute("cascade", _ac.cascade * _screen_h / _scale);
					});
					if (_cb.set) xml.node("commandbar", [&] () {
						/* x and w follow the screen width, every length the screen height */
						xml.attribute("x",          _cb.x * _screen_w / _scale);
						xml.attribute("y",          _cb.y * _screen_h / _scale);
						xml.attribute("w",          _cb.w * _screen_w / _scale);
						xml.attribute("font",       _cb.font * _screen_h / _scale);
						xml.attribute("pad_x",      _cb.pad_x * _screen_h / _scale);
						xml.attribute("pad_y",      _cb.pad_y * _screen_h / _scale);
						xml.attribute("spacing",    _cb.spacing * _screen_h / _scale);
						xml.attribute("tip",        _cb.tip * _screen_h / _scale);
						xml.attribute("greet_font", _cb.greet_font * _screen_h / _scale);
						xml.attribute("sub_font",   _cb.sub_font * _screen_h / _scale);
					});
					if (_ink_set) xml.node("ink", [&] () {
						xml.attribute("accent",      _ink_accent);
						xml.attribute("carbon",      _ink_carbon);
						xml.attribute("carbon_text", _ink_carbon_text);
						xml.attribute("carbon_dim",  _ink_dim);
					});
					if (_fr.set) xml.node("frame", [&] () {
						/* lengths in tenths of a screen pixel (borders are fractions of a pixel) */
						auto px10 = [&] (int v) { return v * _screen_h * 10 / _scale; };
						xml.attribute("border",       px10(_fr.border));
						xml.attribute("glow_reach",   px10(_fr.glow_reach));
						xml.attribute("glow_sigma",   px10(_fr.glow_sigma));
						xml.attribute("glow_alpha",   _fr.glow_alpha);
						xml.attribute("shadow_reach", px10(_fr.shadow_reach));
						xml.attribute("shadow_sigma", px10(_fr.shadow_sigma));
						xml.attribute("shadow_alpha", _fr.shadow_alpha);
						xml.attribute("glow",     _fr_glow);
						xml.attribute("active_a", _fr_active_a);
						xml.attribute("active_b", _fr_active_b);
						xml.attribute("carbon_a", _fr_carbon_a);
						xml.attribute("carbon_b", _fr_carbon_b);
					});
					xml.node("panels", [&] () {
						xml.node("left",   [&] () { xml.attribute("mode", _pl_mode); xml.attribute("size", _pl_size); });
						xml.node("bottom", [&] () { xml.attribute("mode", _pb_mode); xml.attribute("size", _pb_size); });
					});
					xml.node("snaps", [&] () {
						for (int i = 0; i < _snap_count; ++i) {
							Snap const &s = _snaps[i];
							xml.node("snap", [&] () {
								xml.attribute("id", s.id);
								xml.attribute("x",  s.x);   /* normalized 0-100 */
								xml.attribute("w",  s.w);   /* normalized 0-100 */
							});
						}
					});
				});
			});

			log("Theme state published (", _screen_w, "x", _screen_h, "):",
			    " cell0=", _cells[0].x * _screen_w / _scale, ",",
			    _cells[0].y * _screen_h / _scale,
			    " chamfer_pct=", _cells[0].chamfer,
			    " sidebar=", _sb_x * _screen_w / _scale, ",", _sb_y * _screen_h / _scale);
		}
	};
}

void Component::construct(Genode::Env &env)
{
	static Theme::Main main(env);
}
