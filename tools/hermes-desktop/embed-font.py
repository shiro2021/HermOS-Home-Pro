#!/usr/bin/env python3
"""Write a C++ header with the bytes of a font file (the program is then one file)."""
import sys
src, dst, name = sys.argv[1:4]
data = open(src, "rb").read()
with open(dst, "w") as f:
    f.write("// generated by embed-font.py from %s (Inter, SIL Open Font License 1.1)\n#pragma once\n" % src.split('/')[-1])
    f.write("static const unsigned char %s[] = {\n" % name)
    for i in range(0, len(data), 16):
        f.write(",".join(str(b) for b in data[i:i+16]) + ",\n")
    f.write("};\nstatic const unsigned int %s_len = %d;\n" % (name, len(data)))
